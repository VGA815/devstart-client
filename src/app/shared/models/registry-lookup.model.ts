/**
 * Общий словарь сверки с внешними реестрами. Зеркалит `Domain/Registries` на бэке.
 *
 * Живёт отдельно от записей ИС нарочно: реестр Роспатента — первый потребитель, но не последний
 * (следующий — ЕГРЮЛ/ОКВЭД). Если бы каждый реестр заводил свою тройку состояний под своими
 * именами, фронт учил бы два словаря для одного понятия — ровно то, что этот файл предотвращает.
 */

/**
 * Как заявленное значение стоит против локальной копии реестра. Три состояния, и все три
 * показываются: «не найдено» — про запись, «сверка недоступна» — про платформу, и склеивать их
 * нельзя. Недоступность решается **по виду записи**, а не по таблице целиком.
 */
export enum RegistryLookupState {
  RegistryUnavailable = 0,
  Found = 1,
  NotFoundInRegistry = 2,
}

/**
 * Сравнение заявленного значения с реестровым. Именно сравнение: совпадение означает, что реестр
 * и декларация сходятся, — но не что стартап управляет тем, что реестр называет.
 */
export enum DeclaredValueComparison {
  NotComparable = 0,
  Matches = 1,
  Differs = 2,
}
